"""Generate src/guards.rs: the 64 bytes at each memory_guard site and relied-on window in the Smash 13.0.5
main image (a flat image whose file offset is the text offset + 0x100, as `main.uncompressed`).

Usage: python3 -I tools/guard_table.py <main.uncompressed> > src/guards.rs
"""
import hashlib
import sys

OFFSETS = {
    # hooked sites
    "DISPATCH_LIST": 0x3816814,
    "COMPONENT_GET": 0x3810C,
    "LIST_HEAD": 0x37783B4,
    "LIST_NEXT": 0x37783C0,
    "FIELD_A8": 0x59864,
    "REHASH_HEAD": 0x3917574,
    "REHASH_NEXT": 0x39175A0,
    "FREE_PAGES_ABORT": 0x37CAEEC,
    "FREE_PAGES_RESULT": 0x37CAE24,
    # relied-on windows (the loads and calls the repairs depend on)
    "DISPATCH_LIST_RELIED": 0x38167E8,
    "COMPONENT_GET_RELIED": 0x38100,
    "LIST_RELIED": 0x37783B0,
    "FIELD_A8_RELIED": 0x59860,
    "REHASH_RELIED": 0x391756C,
    "FREE_PAGES_RELIED": 0x37CAE10,
}


def main():
    image = open(sys.argv[1], "rb").read()
    print("//! Generated by `tools/guard_table.py` from the Smash 13.0.5 main image")
    print(f"//! (sha256 {hashlib.sha256(image).hexdigest()}): the 64 bytes at each offset.")
    print("//! Do not edit by hand.")
    print()
    for name, offset in OFFSETS.items():
        data = image[0x100 + offset:0x100 + offset + 64]
        rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, 64, 16)]
        print(f"/// `main+{offset:#x}`.")
        print(f"pub const {name}: [u8; 64] = [")
        for row in rows:
            print(f"    {row},")
        print("];")
        print()


if __name__ == "__main__":
    main()
