"""Generate src/guards.rs: the 64 bytes at each memory_guard site and relied-on window in the Smash 13.0.5
main image (a flat image whose file offset is the text offset + 0x100, as `main.uncompressed`).

Usage: python3 -I tools/guard_table.py <main.uncompressed> > src/guards.rs
"""
import hashlib
import sys

OFFSETS = {
    # hooked sites: every one a plain (not PC-relative) instruction
    "DISPATCH_LIST": 0x3816814,      # cmp x26, x27
    "COMPONENT_GET": 0x3810C,        # ldr x0, [x0, x8]
    "LIST_HEAD": 0x37783B0,          # ldr x8, [x21, #0x8]
    "LIST_NEXT": 0x37783BC,          # ldr x8, [x8]
    "FIELD_A8": 0x59860,             # ldr x8, [x0, #0xa8]
    "REHASH_HEAD": 0x391756C,        # ldr x9, [x11, x12]
    "REHASH_NEXT": 0x391758C,        # ldr x13, [x9, #0x10]
    "ABORT_STUB": 0x39C2654,         # ldr x17, [x16, #0x208] in abort's import stub
    "FREE_PAGES_FORCE": 0x37CAE1C,   # mov x1, x21 (diag only)
    # relied-on windows
    "DISPATCH_LIST_RELIED": 0x38167E8,
    "COMPONENT_GET_RELIED": 0x38100,
    "ABORT_STUB_RELIED": 0x39C2650,  # the stub from its adrp
    "ABORT_CALL_RELIED": 0x37CAEEC,  # bl abort after the refused release
    "FREE_PAGES_RELIED": 0x37CAE10,  # mov w8, w21; lsl x21, x8, #16; mov x0, x20; mov x1, x21; bl FreeMemoryPages
    "ALLOC_PAGES_RELIED": 0x37CA654,  # mov w8, w19; lsl x19, x8, #16; mov x0, x21; mov x1, x19; bl AllocateMemoryPages;
                                      # cbnz w0 -> ... bl abort at 0x37ca688
}


def main():
    image = open(sys.argv[1], "rb").read()
    print("//! Generated by `tools/guard_table.py` from the Smash 13.0.5 main image")
    print(f"//! (sha256 {hashlib.sha256(image).hexdigest()}): the 64 bytes at each offset.")
    print("//! Do not edit by hand.")
    print()
    print("/// The 64 bytes at a hooked site.")
    print("pub struct Guard {")
    print("    pub guard: [u8; 64],")
    print("}")
    print()
    for name, offset in OFFSETS.items():
        data = image[0x100 + offset:0x100 + offset + 64]
        rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, 64, 16)]
        print(f"/// `main+{offset:#x}`.")
        if name.endswith("_RELIED"):
            print(f"pub const {name}: [u8; 64] = [")
            for row in rows:
                print(f"    {row},")
            print("];")
        else:
            print(f"pub const {name}: Guard = Guard {{")
            print("    guard: [")
            for row in rows:
                print(f"        {row},")
            print("    ],")
            print("};")
        print()


if __name__ == "__main__":
    main()
